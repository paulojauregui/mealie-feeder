// HTTPClient implements Client over standard net/http against a Mealie v3.25.1 server.
// Pre-conditions: Constructed via NewHTTPClient.
// Post-conditions: Never leaks Authorization token in error messages or logs; bounds error body reads to 4 KiB.
type HTTPClient struct {
	baseURL string
	token   string
	client  *http.Client
}

// NewHTTPClient creates an HTTPClient targeting baseURL with Bearer token and optional *http.Client (nil uses 60s default timeout).
// Pre-conditions: baseURL must be valid http/https URL; token must be non-empty.
// Post-conditions: Trims trailing "/" from baseURL cleanly.
func NewHTTPClient(baseURL, token string, httpClient *http.Client) (*HTTPClient, error) {
	trimmedBase := strings.TrimRight(strings.TrimSpace(baseURL), "/")
	if trimmedBase == "" {
		return nil, errors.New("mealie: baseURL is empty")
	}

	parsed, err := url.Parse(trimmedBase)
	if err != nil || (parsed.Scheme != "http" && parsed.Scheme != "https") || parsed.Host == "" {
		return nil, fmt.Errorf("mealie: invalid baseURL %q: %w", baseURL, err)
	}

	trimmedToken := strings.TrimSpace(token)
	if trimmedToken == "" {
		return nil, errors.New("mealie: API token is empty")
	}

	if httpClient == nil {
		httpClient = &http.Client{
			Timeout: 60 * time.Second,
		}
	}

	return &HTTPClient{
		baseURL: trimmedBase,
		token:   trimmedToken,
		client:  httpClient,
	}, nil
}

// do executes an authenticated request against Mealie and unmarshals JSON response into target.
func (c *HTTPClient) do(ctx context.Context, method, reqPath string, reqBody any, target any) error {
	fullURL := c.baseURL + reqPath

	var bodyReader io.Reader
	if reqBody != nil {
		data, err := json.Marshal(reqBody)
		if err != nil {
			return fmt.Errorf("mealie: marshal request: %w", err)
		}
		bodyReader = bytes.NewReader(data)
	}

	req, err := http.NewRequestWithContext(ctx, method, fullURL, bodyReader)
	if err != nil {
		return fmt.Errorf("mealie: create request: %w", err)
	}

	req.Header.Set("Authorization", "Bearer "+c.token)
	req.Header.Set("Accept", "application/json")
	if reqBody != nil {
		req.Header.Set("Content-Type", "application/json")
	}

	resp, err := c.client.Do(req)
	if err != nil {
		return fmt.Errorf("mealie: %s %s: %w", method, reqPath, err)
	}
	defer resp.Body.Close()

	if resp.StatusCode >= 400 {
		limited := io.LimitReader(resp.Body, 4096)
		errBytes, _ := io.ReadAll(limited)
		return &APIError{
			StatusCode: resp.StatusCode,
			Method:     method,
			Path:       reqPath,
			Detail:     strings.TrimSpace(string(errBytes)),
		}
	}

	if target != nil && resp.StatusCode != http.StatusNoContent {
		if err := json.NewDecoder(resp.Body).Decode(target); err != nil {
			return fmt.Errorf("mealie: decode response from %s: %w", reqPath, err)
		}
	}

	return nil
}

// About queries GET /api/app/about for Mealie version information.
// Pre-conditions: ctx is non-nil.
// Post-conditions: Returns populated AboutResponse on success.
func (c *HTTPClient) About(ctx context.Context) (*AboutResponse, error) {
	var res AboutResponse
	if err := c.do(ctx, http.MethodGet, "/api/app/about", nil, &res); err != nil {
		return nil, err
	}
	return &res, nil
}

// ListAllRecipeURLs paginates across GET /api/recipes collecting all existing recipe summaries and orgURLs.
// Pre-conditions: perPage > 0 (defaults to 100 if <= 0).
// Post-conditions: Stops cleanly when page >= total_pages or total_pages == 0; returns deduplicated summaries.
func (c *HTTPClient) ListAllRecipeURLs(ctx context.Context, perPage int) ([]RecipeSummary, error) {
	if perPage <= 0 {
		perPage = 100
	}

	var allItems []RecipeSummary
	page := 1

	for {
		if err := ctx.Err(); err != nil {
			return nil, err
		}

		reqPath := fmt.Sprintf("/api/recipes?page=%d&perPage=%d", page, perPage)
		var pageRes RecipeListPage
		if err := c.do(ctx, http.MethodGet, reqPath, nil, &pageRes); err != nil {
			return nil, err
		}

		allItems = append(allItems, pageRes.Items...)

		if pageRes.TotalPages <= 0 || page >= pageRes.TotalPages {
			break
		}
		page++
	}

	return allItems, nil
}

// CreateFromHTML posts raw HTML and canonical URL to POST /api/recipes/create/html-or-json.
// Pre-conditions: req.Data and req.URL must be non-empty.
// Post-conditions: Returns slug string generated by Mealie.
func (c *HTTPClient) CreateFromHTML(ctx context.Context, req CreateFromHTMLRequest) (string, error) {
	if strings.TrimSpace(req.Data) == "" {
		return "", errors.New("mealie: CreateFromHTML requires non-empty Data")
	}
	if strings.TrimSpace(req.URL) == "" {
		return "", errors.New("mealie: CreateFromHTML requires non-empty URL")
	}

	var slug string
	if err := c.do(ctx, http.MethodPost, "/api/recipes/create/html-or-json", req, &slug); err != nil {
		return "", err
	}
	return slug, nil
}

// TestScrapeURL sends a URL diagnostic preview request to POST /api/recipes/test-scrape-url.
// Pre-conditions: rawURL must be non-empty.
// Post-conditions: Returns RecipeDetail preview from Mealie scraper.
func (c *HTTPClient) TestScrapeURL(ctx context.Context, rawURL string) (*RecipeDetail, error) {
	if strings.TrimSpace(rawURL) == "" {
		return nil, errors.New("mealie: TestScrapeURL requires non-empty rawURL")
	}

	reqPayload := TestScrapeRequest{
		URL:       rawURL,
		UseOpenAI: false,
	}

	var detail RecipeDetail
	if err := c.do(ctx, http.MethodPost, "/api/recipes/test-scrape-url", reqPayload, &detail); err != nil {
		return nil, err
	}
	return &detail, nil
}

// CreateFromURL requests Mealie to fetch and parse URL directly via POST /api/recipes/create/url.
// Pre-conditions: req.URL must be non-empty; used only when AllowURLFallback is enabled.
// Post-conditions: Returns slug string on successful ingestion.
func (c *HTTPClient) CreateFromURL(ctx context.Context, req CreateFromURLRequest) (string, error) {
	if strings.TrimSpace(req.URL) == "" {
		return "", errors.New("mealie: CreateFromURL requires non-empty URL")
	}

	var slug string
	if err := c.do(ctx, http.MethodPost, "/api/recipes/create/url", req, &slug); err != nil {
		return "", err
	}
	return slug, nil
}

// GetRecipe retrieves full recipe details from GET /api/recipes/{slug}.
// Pre-conditions: slug must be non-empty.
// Post-conditions: Returns RecipeDetail.
func (c *HTTPClient) GetRecipe(ctx context.Context, slug string) (*RecipeDetail, error) {
	trimmedSlug := strings.TrimSpace(slug)
	if trimmedSlug == "" {
		return nil, errors.New("mealie: slug is empty")
	}

	reqPath := "/api/recipes/" + url.PathEscape(trimmedSlug)
	var detail RecipeDetail
	if err := c.do(ctx, http.MethodGet, reqPath, nil, &detail); err != nil {
		return nil, err
	}
	return &detail, nil
}

// DeleteRecipe removes a recipe via DELETE /api/recipes/{slug}.
// Pre-conditions: slug must be non-empty.
// Post-conditions: Deletes recipe or returns APIError if not found.
func (c *HTTPClient) DeleteRecipe(ctx context.Context, slug string) error {
	trimmedSlug := strings.TrimSpace(slug)
	if trimmedSlug == "" {
		return errors.New("mealie: slug is empty")
	}

	reqPath := "/api/recipes/" + url.PathEscape(trimmedSlug)
	return c.do(ctx, http.MethodDelete, reqPath, nil, nil)
}
